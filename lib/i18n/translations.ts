// 帮助函数：翻译政党名
export function translateParty(party: string, lang: Language): string {
  if (lang === 'zh') return PARTY_NAME_CN[party] || party
  return party
}

// 帮助函数：翻译地区名称
export function translateRegion(region: string, lang: Language): string {
  if (lang === 'zh') return REGION_NAME_CN[region] || region
  return region
}

// 帮助函数：翻译国家名称
export function translateNation(nation: string, lang: Language): string {
  if (lang === 'zh') return NATION_NAME_CN[nation] || nation
  return nation
}

